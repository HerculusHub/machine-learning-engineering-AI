"""
Evaluation Agent

Architecture v2.3 (Frozen MVP)

Responsibilities
----------------
Evaluate the draft report generated by ReportAgent.

Validate the report against upstream InformationResult
and ImpactResult when available.

Store structured evaluation results in PipelineContext.

Decide whether one report-refinement pass is required.

Accept the draft directly as final_response when the
evaluation score satisfies the MVP quality threshold.

Optionally persist reflection lessons when a memory object
is available through pipeline metadata.

MVP evaluation flow
-------------------

report_result
    ↓
EvaluationAgent
    ↓
score + strengths + weaknesses + suggestions
    ↓
score >= threshold?
    │
    ├── yes
    │     ↓
    │   final_response = draft
    │
    └── no
          ↓
      requires_report_refinement = True
          ↓
      Step 12D performs ONE refinement pass

Important
---------
The Evaluation Agent does not rewrite reports itself.

Report refinement remains the responsibility of
ReportAgent.

Backward compatibility
----------------------
evaluation_result preserves the original Architecture v2.3
four-field contract:

    score
    strengths
    weaknesses
    suggestions

Pipeline routing information is stored separately in
PipelineContext.metadata.
"""

from __future__ import annotations

from dataclasses import (
    asdict,
    is_dataclass,
)
import json
from typing import Any

from mobile_ai_system.agents.base_agent import (
    BaseAgent,
)
from mobile_ai_system.application.models.pipeline_context import (
    PipelineContext,
)
from mobile_ai_system.core.config import (
    get_settings,
)
from mobile_ai_system.infrastructure.logging.logger import (
    get_logger,
)


settings = get_settings()

logger = get_logger(
    __name__
)


class EvaluationAgent(BaseAgent):
    """
    Pipeline Evaluation Agent.

    Evaluates the report produced by ReportAgent,
    stores structured evaluation output in PipelineContext,
    and determines whether one refinement pass is required.
    """

    # =========================================================
    # MVP quality threshold
    # =========================================================

    QUALITY_THRESHOLD = 0.80

    # =========================================================
    # Identity
    # =========================================================

    @property
    def name(self) -> str:
        """
        Return the pipeline-stage name.
        """

        return "evaluation"

    # =========================================================
    # Execution
    # =========================================================

    def execute(
        self,
        context: PipelineContext,
    ) -> PipelineContext:
        """
        Evaluate the generated draft report.

        Parameters
        ----------
        context
            Shared application pipeline context.

        Returns
        -------
        PipelineContext
            Same context instance with evaluation_result
            populated.

            Routing metadata is also populated:

                evaluation_score
                evaluation_threshold
                requires_report_refinement

            When the draft passes evaluation,
            final_response is populated with the draft.

        Notes
        -----
        A failing draft is NOT rewritten here.

        Step 12D performs at most one refinement through
        ReportAgent.refine().
        """

        logger.info(
            "%s started",
            self.name,
        )

        # -----------------------------------------------------
        # Draft report
        # -----------------------------------------------------

        report = (
            context.report_result
        )

        if not report:

            logger.warning(
                "No report found for evaluation."
            )

            evaluation = (
                self._empty_evaluation()
            )

            context.evaluation_result = (
                evaluation
            )

            context.metadata[
                "evaluation_score"
            ] = 0.0

            context.metadata[
                "evaluation_threshold"
            ] = (
                self.QUALITY_THRESHOLD
            )

            context.metadata[
                "requires_report_refinement"
            ] = True

            context.final_response = None

            return context

        # -----------------------------------------------------
        # Upstream evidence
        # -----------------------------------------------------

        information = (
            context.information_result
        )

        impact = (
            context.impact_result
        )

        # -----------------------------------------------------
        # Evaluate
        # -----------------------------------------------------

        evaluation = (
            self._evaluate_report(
                report=str(
                    report
                ),
                information=(
                    information
                ),
                impact=(
                    impact
                ),
            )
        )

        # -----------------------------------------------------
        # Normalize
        # -----------------------------------------------------

        evaluation = (
            self._normalize_evaluation(
                evaluation
            )
        )

        score = float(
            evaluation[
                "score"
            ]
        )

        # -----------------------------------------------------
        # Quality decision
        # -----------------------------------------------------

        requires_refinement = (
            score
            <
            self.QUALITY_THRESHOLD
        )

        # -----------------------------------------------------
        # Reflection
        # -----------------------------------------------------

        reflection = (
            self._build_reflection(
                evaluation
            )
        )

        reflections = (
            context.metadata.setdefault(
                "reflections",
                [],
            )
        )

        reflections.append(
            reflection
        )

        # -----------------------------------------------------
        # Save evaluation
        # -----------------------------------------------------

        context.evaluation_result = (
            evaluation
        )

        context.metadata[
            "evaluation_score"
        ] = score

        context.metadata[
            "evaluation_threshold"
        ] = (
            self.QUALITY_THRESHOLD
        )

        context.metadata[
            "requires_report_refinement"
        ] = (
            requires_refinement
        )

        # -----------------------------------------------------
        # Accept passing draft immediately
        # -----------------------------------------------------

        if not requires_refinement:

            context.final_response = str(
                report
            )

        else:

            # Step 12D will populate final_response after
            # exactly one ReportAgent.refine() call.

            context.final_response = None

        # -----------------------------------------------------
        # Save reflection to memory
        # -----------------------------------------------------

        self._save_reflection_to_memory(
            context=context,
            reflection=reflection,
        )

        logger.info(
            (
                "Evaluation complete | "
                "score=%.2f | threshold=%.2f | "
                "requires_refinement=%s"
            ),
            score,
            self.QUALITY_THRESHOLD,
            requires_refinement,
        )

        logger.info(
            "%s finished",
            self.name,
        )

        return context

    # =========================================================
    # Report evaluation
    # =========================================================

    def _evaluate_report(
        self,
        report: str,
        information: Any | None = None,
        impact: Any | None = None,
    ) -> dict[str, Any]:
        """
        Evaluate report through LLM when available.

        The evaluator receives the draft plus upstream
        Information and Impact evidence so it can detect:

        - unsupported claims
        - inconsistent metrics
        - missing analysis
        - weak recommendations

        Falls back to heuristic evaluation when no LLM tool
        is configured.
        """

        llm = (
            self._get_llm_tool()
        )

        if llm is None:

            logger.warning(
                "LLMTool is unavailable. "
                "Falling back to heuristic evaluation."
            )

            return (
                self._heuristic_evaluation(
                    report
                )
            )

        prompt = (
            self._build_prompt(
                report=report,
                information=information,
                impact=impact,
            )
        )

        try:

            response = llm.generate(
                provider=(
                    settings
                    .evaluation_agent_provider
                ),
                model=(
                    settings
                    .evaluation_agent_model
                ),
                prompt=prompt,
            )

            # -------------------------------------------------
            # String JSON response
            # -------------------------------------------------

            if isinstance(
                response,
                str,
            ):

                cleaned = (
                    self._clean_json_response(
                        response
                    )
                )

                return json.loads(
                    cleaned
                )

            # -------------------------------------------------
            # Already structured
            # -------------------------------------------------

            if isinstance(
                response,
                dict,
            ):

                return response

            raise ValueError(
                "Unsupported LLM response type."
            )

        except Exception as exc:

            logger.exception(
                "LLM evaluation failed: %s",
                exc,
            )

            return {
                "score": 0.5,
                "strengths": [],
                "weaknesses": [
                    "LLM evaluation failed."
                ],
                "suggestions": [
                    "Retry evaluation."
                ],
            }

    # =========================================================
    # LLM
    # =========================================================

    def _get_llm_tool(
        self,
    ) -> Any | None:
        """
        Return configured LLMTool if available.
        """

        tools = getattr(
            self,
            "tools",
            None,
        )

        if tools is None:
            return None

        return tools.get(
            "llm",
        )

    # =========================================================
    # Evaluation prompt
    # =========================================================

    @classmethod
    def _build_prompt(
        cls,
        report: str,
        information: Any | None = None,
        impact: Any | None = None,
    ) -> str:
        """
        Build the MVP report-evaluation prompt.

        The report is evaluated against available upstream
        evidence rather than in isolation.
        """

        information_summary = (
            cls._serialize_value(
                information
            )
        )

        impact_summary = (
            cls._serialize_value(
                impact
            )
        )

        return f"""
You are evaluating an analytical telecom report.

Evaluate the DRAFT REPORT against the supplied
INFORMATION ANALYSIS and IMPACT ANALYSIS.

Evaluate the report using the following criteria:

1. Completeness
   - The report should cover the important competitor,
     customer, impact, and recommendation findings.

2. Accuracy
   - Claims must be consistent with the Information Analysis
     and Impact Analysis.
   - Penalize unsupported facts, metrics, financial values,
     and causal claims.

3. Logical coherence
   - Conclusions should follow from the supplied analysis.

4. Actionability
   - Recommendations should be concrete and relevant to the
     identified risks and opportunities.

5. Overall quality
   - The report should be clear, concise, structured, and
     useful to executive decision makers.

Return a score between 0.0 and 1.0.

A score of 0.80 or higher means the report is acceptable
without another MVP refinement.

Return ONLY valid JSON in the following format:

{{
    "score": 0.0,
    "strengths": [
        "...",
        "..."
    ],
    "weaknesses": [
        "...",
        "..."
    ],
    "suggestions": [
        "...",
        "..."
    ]
}}

INFORMATION ANALYSIS:

{information_summary}

IMPACT ANALYSIS:

{impact_summary}

DRAFT REPORT:

{report}
""".strip()

    # =========================================================
    # JSON response cleanup
    # =========================================================

    @staticmethod
    def _clean_json_response(
        response: str,
    ) -> str:
        """
        Remove common Markdown JSON fences returned by LLMs.

        This keeps the MVP tolerant without adding a separate
        structured-output subsystem.
        """

        text = response.strip()

        if text.startswith(
            "```json"
        ):

            text = text[
                len(
                    "```json"
                ):
            ].strip()

        elif text.startswith(
            "```"
        ):

            text = text[
                len(
                    "```"
                ):
            ].strip()

        if text.endswith(
            "```"
        ):

            text = text[
                :-
                len(
                    "```"
                )
            ].strip()

        return text

    # =========================================================
    # Heuristic fallback
    # =========================================================

    @staticmethod
    def _heuristic_evaluation(
        report: str,
    ) -> dict[str, Any]:
        """
        Frozen MVP heuristic evaluation.

        Preserve the original Architecture v2.3 behavior.

        Reports longer than 80 characters receive the
        high-confidence placeholder score.

        Shorter reports receive the lower fallback score.
        """

        score = (
            1.0
            if len(
                report
            ) > 80
            else 0.5
        )

        return {
            "score": score,
            "strengths": [],
            "weaknesses": [],
            "suggestions": [],
        }

    # =========================================================
    # Normalization
    # =========================================================

    @staticmethod
    def _normalize_evaluation(
        evaluation: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Normalize evaluation output.

        The canonical MVP score range is:

            0.0 <= score <= 1.0

        Scores outside the interval are clamped.

        This preserves the original Architecture v2.3
        evaluation contract.
        """

        score = float(
            evaluation.get(
                "score",
                0.5,
            )
        )

        score = max(
            0.0,
            min(
                1.0,
                score,
            ),
        )

        strengths = (
            evaluation.get(
                "strengths",
                [],
            )
        )

        weaknesses = (
            evaluation.get(
                "weaknesses",
                [],
            )
        )

        suggestions = (
            evaluation.get(
                "suggestions",
                [],
            )
        )

        if not isinstance(
            strengths,
            list,
        ):
            strengths = []

        if not isinstance(
            weaknesses,
            list,
        ):
            weaknesses = []

        if not isinstance(
            suggestions,
            list,
        ):
            suggestions = []

        return {
            "score": score,

            "strengths": [
                str(
                    item
                )
                for item in strengths
            ],

            "weaknesses": [
                str(
                    item
                )
                for item in weaknesses
            ],

            "suggestions": [
                str(
                    item
                )
                for item in suggestions
            ],
        }

    # =========================================================
    # Generic serialization
    # =========================================================

    @classmethod
    def _serialize_value(
        cls,
        value: Any,
    ) -> Any:
        """
        Convert structured upstream analysis into
        prompt-friendly values.

        No new analytical calculations are performed.
        """

        if value is None:
            return None

        to_dict = getattr(
            value,
            "to_dict",
            None,
        )

        if callable(
            to_dict
        ):

            return cls._serialize_value(
                to_dict()
            )

        if is_dataclass(
            value
        ):

            return cls._serialize_value(
                asdict(
                    value
                )
            )

        if isinstance(
            value,
            dict,
        ):

            return {
                str(
                    key
                ): cls._serialize_value(
                    item
                )
                for key, item in value.items()
            }

        if isinstance(
            value,
            (
                list,
                tuple,
            ),
        ):

            return [
                cls._serialize_value(
                    item
                )
                for item in value
            ]

        return value

    # =========================================================
    # Reflection
    # =========================================================

    @staticmethod
    def _build_reflection(
        evaluation: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Convert evaluation output into a reflection record.

        Reflection preserves the original Architecture v2.3
        structure.
        """

        suggestions = (
            evaluation[
                "suggestions"
            ]
        )

        lesson = (
            "\n".join(
                str(
                    item
                )
                for item in suggestions
            )
            if suggestions
            else "No improvement suggestions."
        )

        return {
            "score": (
                evaluation[
                    "score"
                ]
            ),

            "strengths": (
                evaluation[
                    "strengths"
                ]
            ),

            "weaknesses": (
                evaluation[
                    "weaknesses"
                ]
            ),

            "suggestions": (
                suggestions
            ),

            "lesson": (
                lesson
            ),
        }

    # =========================================================
    # Memory
    # =========================================================

    @staticmethod
    def _save_reflection_to_memory(
        context: PipelineContext,
        reflection: dict[str, Any],
    ) -> None:
        """
        Persist reflection when a memory object is available.

        Frozen MVP obtains memory through PipelineContext
        metadata rather than creating a direct dependency from
        the Evaluation Agent.
        """

        memory = (
            context.metadata.get(
                "memory",
            )
        )

        if memory is None:
            return

        save_reflection = getattr(
            memory,
            "save_reflection",
            None,
        )

        if not callable(
            save_reflection
        ):
            return

        save_reflection(
            lesson=(
                reflection[
                    "lesson"
                ]
            ),
            source="evaluation",
            score=(
                reflection[
                    "score"
                ]
            ),
        )

    # =========================================================
    # Empty result
    # =========================================================

    @staticmethod
    def _empty_evaluation() -> dict[str, Any]:
        """
        Return evaluation used when no report exists.

        Preserve the original evaluation-result contract.
        """

        return {
            "score": 0.0,

            "strengths": [],

            "weaknesses": [
                "No report available for evaluation."
            ],

            "suggestions": [
                "Generate a report before evaluation."
            ],
        }